<?php

declare(strict_types=1);

namespace MergeMultisite\Report;

/**
 * Writes the post-migration to-do list (PLAN.md §10).
 *
 * The migration cannot finish every task on its own.
 * Permalink rewrite rules, the static-front-page decision, theme
 * activation, and plugin activation are all deliberate
 * destination-side steps.
 * This writer turns the run's report data into one actionable
 * `to-do-list.md` for the user.
 *
 * Contents:
 *  - the destination admin URL and login note;
 *  - the permalink flush step (pretty URLs 404 until rewrite rules
 *    regenerate);
 *  - the homepage step, with the migrated front page's destination
 *    post ID when the source data was captured;
 *  - the theme step;
 *  - per-plugin install commands for the union of source-active
 *    plugins, each with `--force`, one with `--activate` and one
 *    without;
 *  - every report and log file written this run.
 *
 * Pure formatting, no DB, fully unit-testable.
 *
 * @phpstan-type TodoData array{
 *     generated_at: string,
 *     destination_admin_url: string,
 *     login_note: string,
 *     front_page: TodoFrontPage|null,
 *     active_plugins_union: array<int, string>,
 *     report_paths: array<int, string>,
 *     log_path: string
 * }
 *
 * @phpstan-type TodoFrontPage array{blog_id: int, show_on_front: string, page_on_front: int, page_on_front_destination: int|null, page_for_posts: int, page_for_posts_destination: int|null}
 *
 * @package MergeMultisite
 */
final class PostMigrationTodoWriter {

	/**
	 * @param TodoData $data
	 */
	public function toMarkdown( array $data ): string {
		$lines = array(
			'# Post-migration to-do list',
			'',
			sprintf( 'Generated by merge-multisite on %s.', $data['generated_at'] ),
			'',
			'## Destination admin',
			'',
			sprintf( 'Admin URL: %s', $data['destination_admin_url'] ),
			$data['login_note'],
			'',
			'## Permalinks',
			'',
			'The permalink structure migrated, but the rewrite rules did not.',
			'WordPress regenerates them when the permalink settings are saved.',
			'Pretty URLs return 404 until then; ?p=N query URLs still work.',
			'',
			'1. Visit Settings → Permalinks in wp-admin.',
			'2. Press Save (no change needed).',
			'',
			'Or from the command line, in the destination project:',
			'',
			'    wp rewrite flush',
			'',
		);

		$this->appendHomepage( $lines, $data['front_page'] );
		$this->appendTheme( $lines );
		$this->appendPlugins( $lines, $data['active_plugins_union'] );
		$this->appendReports( $lines, $data );

		return implode( "\n", $lines ) . "\n";
	}

	/**
	 * Write `to-do-list.md` into `$directory` (created if needed).
	 *
	 * @param TodoData $data
	 *
	 * @return string The basename written.
	 */
	public function writeAll( array $data, string $directory ): string {
		if ( ! is_dir( $directory ) ) {
			mkdir( $directory, 0775, true );
		}

		$name = 'to-do-list.md';
		file_put_contents( rtrim( $directory, '/' ) . '/' . $name, $this->toMarkdown( $data ) );

		return $name;
	}

	/**
	 * @param string[]           $lines
	 * @param TodoFrontPage|null $frontPage
	 */
	private function appendHomepage( array &$lines, ?array $frontPage ): void {
		$lines[] = '## Homepage (Settings → Reading)';
		$lines[] = '';
		$lines[] = 'Your homepage displays is set to "Your Latest Posts".';
		$lines[] = 'Set it to "A static page" and select the migrated front page.';

		if ( $frontPage !== null ) {
			$page = $frontPage['page_on_front_destination'];
			if ( $page !== null ) {
				$lines[] = '';
				$lines[] = 'Migrated front page: site ' . $frontPage['blog_id'] . ', destination post ID ' . $page . '.';
				$lines[] = '';
				$lines[] = 'Or from the command line:';
				$lines[] = '';
				$lines[] = '    wp option update show_on_front page';
				$lines[] = '    wp option update page_on_front ' . $page;
				if ( $frontPage['page_for_posts_destination'] !== null ) {
					$lines[] = '    wp option update page_for_posts ' . $frontPage['page_for_posts_destination'];
				}
			} else {
				$lines[] = '';
				$lines[] = 'The source front page was not migrated (post ID '
					. $frontPage['page_on_front'] . ' on site ' . $frontPage['blog_id']
					. '); pick a migrated page manually.';
			}
		}

		$lines[] = '';
	}

	/**
	 * @param string[] $lines
	 */
	private function appendTheme( array &$lines ): void {
		$lines[] = '## Theme';
		$lines[] = '';
		$lines[] = 'Activate the intended destination theme.';
		$lines[] = 'Theme settings and theme_mods are not migrated by design.';
		$lines[] = 'Reapply Customizer Custom CSS if the migrated design needs it.';
		$lines[] = '';
		$lines[] = '    wp theme activate <theme-slug>';
		$lines[] = '';
	}

	/**
	 * @param string[] $lines
	 * @param string[] $pluginSlugs
	 */
	private function appendPlugins( array &$lines, array $pluginSlugs ): void {
		$lines[] = '## Plugins to install on the destination';
		$lines[] = '';
		$lines[] = 'The union of plugins active on the included source sites:';
		$lines[] = '';

		if ( $pluginSlugs === array() ) {
			$lines[] = '_No active source plugins detected._';
			$lines[] = '';
			return;
		}

		$lines[] = implode( ', ', $pluginSlugs );
		$lines[] = '';
		$lines[] = 'Run in the destination project directory (e.g. ~/sites/destination-wp, via `lando wp` or your wp-cli):';
		$lines[] = '';

		foreach ( $pluginSlugs as $slug ) {
			$lines[] = '    wp plugin install ' . $slug . ' --force';
			$lines[] = '    wp plugin install ' . $slug . ' --force --activate';
		}

		$lines[] = '';
		$lines[] = '`--force` reinstalls plugins already present on the destination.';
		$lines[] = 'The second command activates the plugin as well.';
		$lines[] = '';
	}

	/**
	 * @param string[] $lines
	 * @param TodoData $data
	 */
	private function appendReports( array &$lines, array $data ): void {
		$lines[] = '## Reports and logs written this run';
		$lines[] = '';
		$lines[] = 'All files live under var/ inside the merge-multisite project:';
		$lines[] = '';

		foreach ( $data['report_paths'] as $path ) {
			$lines[] = '- ' . $path;
		}
		$lines[] = '- ' . $data['log_path'];
		$lines[] = '';
	}
}
